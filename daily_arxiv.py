def http_session() -> requests.Session:
    session = requests.Session()
    repo = os.environ.get("GITHUB_REPOSITORY", "")
    contact = f" (+https://github.com/{repo})" if repo else ""
    session.headers["User-Agent"] = f"photo-geometry-arxiv-daily/{__version__}{contact}"
    return session


class HFLinkResolver:
    """Looks up ``githubRepo`` / ``projectPage`` on the Hugging Face Papers API.

    ``lookup`` returns ``None`` when no request was made (budget exhausted,
    disabled after repeated errors, rate limited) and a ``(code, project)``
    tuple otherwise (empty strings when the paper has no links).
    """

    def __init__(
        self,
        session: requests.Session | None = None,
        max_lookups: int = 300,
        delay_seconds: float = 0.4,
        max_consecutive_errors: int = 5,
        sleep: Callable[[float], None] | None = None,
    ) -> None:
        self.session = session or http_session()
        self.max_lookups = max_lookups
        self.delay_seconds = delay_seconds
        self.max_consecutive_errors = max_consecutive_errors
        self._sleep = sleep if sleep is not None else time.sleep  # looked up now, so tests can patch it
        self.used = 0
        self.found = 0
        self._errors = 0
        self.disabled = max_lookups <= 0

    def lookup(self, arxiv_id: str) -> tuple[str, str] | None:
        if self.disabled or self.used >= self.max_lookups:
            return None
        if not NEW_STYLE_ID_RE.match(arxiv_id):
            return ("", "")
        if self.used:
            self._sleep(self.delay_seconds)
        self.used += 1
        try:
            response = self.session.get(HF_PAPER_API_URL.format(id=arxiv_id), timeout=(5, 20))
        except requests.RequestException as exc:
            return self._error(f"request failed for {arxiv_id}: {exc}")
        if response.status_code == 404:
            self._errors = 0
            return ("", "")
        if response.status_code == 429:
            self.disabled = True
            LOG.warning("Hugging Face API rate limit reached; skipping remaining code-link lookups")
            return None
        if response.status_code != 200:
            return self._error(f"HTTP {response.status_code} for {arxiv_id}")
        try:
            data = response.json()
        except ValueError:
            return self._error(f"invalid JSON for {arxiv_id}")
        self._errors = 0
        if not isinstance(data, dict):
            return ("", "")
        code = normalize_code_url(str(data.get("githubRepo") or ""))
        project = normalize_project_url(str(data.get("projectPage") or ""))
        if code or project:
            self.found += 1
        return (code, project)

    def _error(self, message: str) -> None:
        self._errors += 1
        LOG.warning("Hugging Face lookup: %s", message)
        if self._errors >= self.max_consecutive_errors:
            self.disabled = True
            LOG.warning("Hugging Face lookups disabled for this run after %d consecutive errors", self._errors)
        return None


