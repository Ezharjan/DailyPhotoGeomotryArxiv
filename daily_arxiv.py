def render_site(archive: Mapping[str, Any], cfg: Config) -> dict[Path, str]:
    """Return {path: content} for every generated page."""
    data = build_site_data(archive, cfg)
    pages: dict[Path, str] = {
        cfg.site_dir / "index.html": render_home(data),
        cfg.site_dir / "explorer.html": render_explorer(data),
        cfg.site_dir / "topics" / "index.html": render_topics_index(data),
    }
    for order, topic in enumerate(cfg.topics, start=1):
        pages[cfg.site_dir / "topics" / f"{topic.slug}.html"] = render_topic_page(data, topic, order)
    return pages


def remove_stale_pages(cfg: Config, keep: Iterable[Path]) -> list[Path]:
    """Delete generated topic pages that no longer correspond to a topic."""
    keep_set = {p.resolve() for p in keep}
    removed = []
    topic_dir = cfg.site_dir / "topics"
    if not topic_dir.is_dir():
        return removed
    for path in sorted(topic_dir.glob("*.html")):
        if path.resolve() in keep_set:
            continue
        try:
            head = path.read_text(encoding="utf-8")[:400]
        except (OSError, UnicodeDecodeError):
            continue
        if GENERATED_MARKER in head:
            path.unlink()
            removed.append(path)
    return removed


def write_outputs(archive: dict[str, Any], cfg: Config, data_changed: bool) -> int:
    """Write the archive and site pages; returns the number of files written."""
    if data_changed:
        archive["updated_at"] = iso_utc(utc_now())
    archive["schema_version"] = SCHEMA_VERSION
    archive["topics"] = topics_metadata(cfg)
    written = int(write_if_changed(cfg.data_file, serialize_archive(archive)))
    pages = render_site(archive, cfg)
    for path, content in pages.items():
        written += int(write_if_changed(path, content))
    for path in remove_stale_pages(cfg, pages):
        LOG.info("removed stale page %s", path)
        written += 1
    return written


