_TRAILING_PUNCT = ".,;:!?*'\""


def _clean_url(url: str) -> str:
    url = url.strip()
    if not re.match(r"^https?://", url, re.IGNORECASE):
        url = "https://" + url
    while url and url[-1] in _TRAILING_PUNCT:
        url = url[:-1]
    # Drop unbalanced closing parentheses picked up from surrounding prose.
    while url.endswith(")") and url.count(")") > url.count("("):
        url = url[:-1]
        while url and url[-1] in _TRAILING_PUNCT:
            url = url[:-1]
    return url


def _host(url: str) -> str:
    try:
        host = (urlsplit(url).hostname or "").lower()
    except ValueError:
        return ""
    return host[4:] if host.startswith("www.") else host


def normalize_code_url(url: str) -> str:
    """Return the canonical repository URL for a code-hosting link, else ''."""
    url = _clean_url(url)
    host = _host(url)
    if host not in CODE_HOSTS:
        return ""
    try:
        path = urlsplit(url).path
    except ValueError:
        return ""
    segments = [seg for seg in path.split("/") if seg]
    if host == "github.com":
        if len(segments) < 2 or segments[0].lower() in GITHUB_RESERVED_OWNERS:
            return ""
        owner, repo = segments[0], segments[1]
    else:
        # GitLab and friends allow nested groups; stop at '-' / tree / blob markers.
        kept: list[str] = []
        for seg in segments:
            if seg in ("-", "tree", "blob", "src", "issues", "wiki"):
                break
            kept.append(seg)
        if len(kept) < 2:
            return ""
        owner, repo = "/".join(kept[:-1]), kept[-1]
    if repo.lower().endswith(".git"):
        repo = repo[:-4]
    name_ok = re.compile(r"^[A-Za-z0-9_.-]+$")
    if not repo or not all(name_ok.match(part) for part in owner.split("/") + [repo]):
        return ""
    return f"https://{host}/{owner}/{repo}"


def normalize_project_url(url: str) -> str:
    url = _clean_url(url)
    host = _host(url)
    if not host or host in CODE_HOSTS or "." not in host:
        return ""
    if any(host == bad or host.endswith("." + bad) for bad in NON_PROJECT_HOSTS):
        return ""
    if not re.match(r"^https?://", url, re.IGNORECASE):
        return ""
    return url


def extract_links(text: str) -> tuple[str, str]:
    """Find the first code repository and the first project/web page URL in text."""
    code = project = ""
    for match in URL_RE.finditer(text or ""):
        raw = match.group(0)
        if not code:
            code = normalize_code_url(raw)
            if code:
                continue
        if not project:
            project = normalize_project_url(raw)
        if code and project:
            break
    return code, project


