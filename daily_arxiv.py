def prune_subsumed(phrases: Sequence[str]) -> tuple[str, ...]:
    """Drop phrases that contain another phrase of the list as a token sequence.

    arXiv matches phrases token by token, so ``ti:"focal length"`` already
    matches every title that ``ti:"focal length estimation"`` would match.
    """
    tokens = [phrase_key(p).split() for p in phrases]

    def contains(longer: list[str], shorter: list[str]) -> bool:
        n = len(shorter)
        return any(longer[i:i + n] == shorter for i in range(len(longer) - n + 1))

    kept = []
    for i, phrase in enumerate(phrases):
        if not any(j != i and len(tokens[j]) < len(tokens[i]) and contains(tokens[i], tokens[j])
                   for j in range(len(phrases))):
            kept.append(phrase)
    return tuple(kept)


def build_query(topic: Topic, categories: Sequence[str]) -> str:
    """Build the arXiv API ``search_query`` for a topic.

    ``(ti:"a" OR ti:"b" OR abs:"b" ...) AND (cat:cs.CV OR ...) ANDNOT (ti:"x" ...)``
    """
    title_terms = prune_subsumed(dedupe_phrases(topic.title_keywords + topic.keywords))
    abstract_terms = prune_subsumed(dedupe_phrases(topic.keywords))
    clauses = [f'ti:"{p}"' for p in title_terms] + [f'abs:"{p}"' for p in abstract_terms]
    if not clauses:
        raise ConfigError(f"topic {topic.slug!r} has no keywords")
    query = "(" + " OR ".join(clauses) + ")"
    if categories:
        query += " AND (" + " OR ".join(f"cat:{c}" for c in categories) + ")"
    if topic.exclude_title_keywords:
        excluded = " OR ".join(f'ti:"{p}"' for p in topic.exclude_title_keywords)
        query = f"({query}) ANDNOT ({excluded})"
    return query


def arxiv_api_url(query: str, max_results: int = 50) -> str:
    """Browser-friendly arXiv API URL for a query (newest first)."""
    params = {
        "search_query": query,
        "sortBy": "submittedDate",
        "sortOrder": "descending",
        "start": 0,
        "max_results": max_results,
    }
    return f"{ARXIV_API_URL}?{urlencode(params, quote_via=quote)}"


