@dataclass(frozen=True)
class Topic:
    slug: str
    name: str
    description: str
    title_keywords: tuple[str, ...]
    keywords: tuple[str, ...]
    exclude_title_keywords: tuple[str, ...] = ()


@dataclass(frozen=True)
class Config:
    root: Path
    categories: tuple[str, ...]
    max_results_per_topic: int
    request_delay_seconds: float
    num_retries: int
    huggingface_lookup: bool
    max_lookups_per_run: int
    recheck_days: int
    data_file: Path
    site_dir: Path
    home_latest_papers: int
    topic_page_max_papers: int
    topics: tuple[Topic, ...]

    def topic(self, slug: str) -> Topic | None:
        for topic in self.topics:
            if topic.slug == slug:
                return topic
        return None


def _normalize_space(text: str) -> str:
    return " ".join(str(text).split())


def phrase_key(phrase: str) -> str:
    """Normalized form used to de-duplicate phrases.

    arXiv search is case-insensitive and treats hyphens as spaces, so
    "single-view metrology" and "Single View Metrology" are the same query.
    """
    return _normalize_space(phrase.replace("-", " ")).casefold()


def dedupe_phrases(phrases: Iterable[str]) -> tuple[str, ...]:
    seen: set[str] = set()
    out: list[str] = []
    for phrase in phrases:
        key = phrase_key(phrase)
        if key and key not in seen:
            seen.add(key)
            out.append(phrase)
    return tuple(out)


def slugify(text: str) -> str:
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "topic"


def _phrase_list(value: Any, where: str) -> tuple[str, ...]:
    if value is None:
        return ()
    if isinstance(value, str):
        value = [value]
    if not isinstance(value, (list, tuple)):
        raise ConfigError(f"{where} must be a list of phrases")
    phrases: list[str] = []
    for item in value:
        if not isinstance(item, str) or not item.strip():
            raise ConfigError(f"{where} contains an empty or non-text entry: {item!r}")
        phrase = _normalize_space(item)
        if FORBIDDEN_PHRASE_CHARS.search(phrase):
            raise ConfigError(f'{where}: phrase {phrase!r} must not contain any of  " ( ) : \\')
        phrases.append(phrase)
    return dedupe_phrases(phrases)


def _get_int(section: Mapping[str, Any], key: str, default: int, minimum: int, where: str) -> int:
    value = section.get(key, default)
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise ConfigError(f"{where}.{key} must be an integer >= {minimum}, got {value!r}")
    return value


def _get_section(raw: Mapping[str, Any], key: str) -> Mapping[str, Any]:
    section = raw.get(key) or {}
    if not isinstance(section, Mapping):
        raise ConfigError(f"'{key}' must be a mapping")
    return section


def _topics_from_legacy(raw_keywords: Mapping[str, Any]) -> list[dict[str, Any]]:
    """Convert the legacy ``keywords: {name: {filters: [...]}}`` format."""
    LOG.warning("config uses the legacy 'keywords:' format; please migrate to 'topics:' (see README)")
    topics = []
    for name, spec in raw_keywords.items():
        filters = spec.get("filters") if isinstance(spec, Mapping) else spec
        topics.append({"slug": slugify(str(name)), "name": str(name), "keywords": filters})
    return topics


def load_config(path: str | os.PathLike[str]) -> Config:
    """Load and validate ``config.yaml``. Paths are relative to the config file."""
    config_path = Path(path).resolve()
    if not config_path.is_file():
        raise ConfigError(f"config file not found: {config_path}")
    with config_path.open("r", encoding="utf-8") as fh:
        raw = yaml.safe_load(fh) or {}
    if not isinstance(raw, Mapping):
        raise ConfigError("config root must be a mapping")
    root = config_path.parent

    arxiv_cfg = _get_section(raw, "arxiv")
    links_cfg = _get_section(raw, "code_links")
    out_cfg = _get_section(raw, "output")

    categories = arxiv_cfg.get("categories", ["cs.CV", "cs.RO", "cs.GR", "eess.IV"])
    if not isinstance(categories, (list, tuple)) or not categories:
        raise ConfigError("arxiv.categories must be a non-empty list")
    for cat in categories:
        if not isinstance(cat, str) or not CATEGORY_RE.match(cat):
            raise ConfigError(f"arxiv.categories: invalid arXiv category {cat!r}")

    delay = arxiv_cfg.get("request_delay_seconds", 3.5)
    if isinstance(delay, bool) or not isinstance(delay, (int, float)) or delay < 3:
        raise ConfigError("arxiv.request_delay_seconds must be a number >= 3 (arXiv API terms of use)")

    hf_lookup = links_cfg.get("huggingface_lookup", True)
    if not isinstance(hf_lookup, bool):
        raise ConfigError("code_links.huggingface_lookup must be true or false")

    raw_topics = raw.get("topics")
    if raw_topics is None and isinstance(raw.get("keywords"), Mapping):
        raw_topics = _topics_from_legacy(raw["keywords"])
    if not isinstance(raw_topics, list) or not raw_topics:
        raise ConfigError("'topics' must be a non-empty list")

    topics: list[Topic] = []
    slugs: set[str] = set()
    names: set[str] = set()
    for index, item in enumerate(raw_topics, start=1):
        where = f"topics[{index}]"
        if not isinstance(item, Mapping):
            raise ConfigError(f"{where} must be a mapping")
        name = _normalize_space(item.get("name") or "")
        if not name:
            raise ConfigError(f"{where}.name is required")
        slug = str(item.get("slug") or slugify(name)).strip()
        if not SLUG_RE.match(slug):
            raise ConfigError(f"{where}.slug {slug!r} must be lowercase letters/digits separated by '-'")
        if slug in slugs:
            raise ConfigError(f"duplicate topic slug {slug!r}")
        if name.casefold() in names:
            raise ConfigError(f"duplicate topic name {name!r}")
        slugs.add(slug)
        names.add(name.casefold())
        keywords = _phrase_list(item.get("keywords"), f"{where}.keywords")
        title_keywords = _phrase_list(item.get("title_keywords"), f"{where}.title_keywords")
        if not keywords and not title_keywords:
            raise ConfigError(f"{where} ({name}) needs at least one of 'keywords' or 'title_keywords'")
        topics.append(
            Topic(
                slug=slug,
                name=name,
                description=_normalize_space(item.get("description") or ""),
                title_keywords=title_keywords,
                keywords=keywords,
                exclude_title_keywords=_phrase_list(
                    item.get("exclude_title_keywords"), f"{where}.exclude_title_keywords"
                ),
            )
        )

    site_dir = (root / str(out_cfg.get("site_dir", "docs"))).resolve()
    data_file = (root / str(out_cfg.get("data_file", "docs/photo-geometry-arxiv-daily.json"))).resolve()
    if site_dir not in data_file.parents:
        raise ConfigError("output.data_file must be inside output.site_dir so the website can load it")
    if data_file.suffix.lower() != ".json":
        raise ConfigError("output.data_file must be a .json file")
    data_url_path = data_file.relative_to(site_dir).as_posix()
    if not re.match(r"^[A-Za-z0-9._/-]+$", data_url_path) or any(
        segment.startswith(("_", ".")) for segment in data_url_path.split("/")
    ):
        raise ConfigError(
            "output.data_file may only contain letters, digits, '.', '_', '-' and '/', "
            "and must not start with '_' or '.' (Jekyll would not publish it)"
        )

    return Config(
        root=root,
        categories=tuple(categories),
        max_results_per_topic=_get_int(arxiv_cfg, "max_results_per_topic", 100, 1, "arxiv"),
        request_delay_seconds=float(delay),
        num_retries=_get_int(arxiv_cfg, "num_retries", 5, 0, "arxiv"),
        huggingface_lookup=hf_lookup,
        max_lookups_per_run=_get_int(links_cfg, "max_lookups_per_run", 300, 0, "code_links"),
        recheck_days=_get_int(links_cfg, "recheck_days", 60, 1, "code_links"),
        data_file=data_file,
        site_dir=site_dir,
        home_latest_papers=_get_int(out_cfg, "home_latest_papers", 60, 1, "output"),
        topic_page_max_papers=_get_int(out_cfg, "topic_page_max_papers", 300, 1, "output"),
        topics=tuple(topics),
    )


