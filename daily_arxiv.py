def utc_now() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0)


def iso_utc(moment: dt.datetime) -> str:
    return moment.astimezone(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def parse_iso_utc(value: str) -> dt.datetime | None:
    try:
        moment = dt.datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except (TypeError, ValueError):
        return None
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=dt.timezone.utc)
    return moment.astimezone(dt.timezone.utc)


def empty_archive() -> dict[str, Any]:
    return {"schema_version": SCHEMA_VERSION, "updated_at": None, "topics": [], "papers": {}}


def _clean_record(raw: Mapping[str, Any]) -> dict[str, Any] | None:
    arxiv_id = str(raw.get("id") or "").strip()
    title = _normalize_space(raw.get("title") or "")
    published = str(raw.get("published") or "")
    if not arxiv_id or not title or not DATE_RE.match(published):
        return None
    updated = str(raw.get("updated") or published)
    authors = [str(a) for a in (raw.get("authors") or []) if str(a).strip()]
    try:
        n_authors = max(int(raw.get("n_authors") or len(authors)), len(authors))
    except (TypeError, ValueError):
        n_authors = len(authors)
    topics = [str(t) for t in (raw.get("topics") or []) if str(t).strip()]
    return {
        "id": arxiv_id,
        "title": title,
        "authors": authors,
        "n_authors": n_authors,
        "published": published,
        "updated": updated if DATE_RE.match(updated) else published,
        "primary_category": str(raw.get("primary_category") or ""),
        "categories": [str(c) for c in (raw.get("categories") or []) if str(c).strip()],
        "comment": str(raw.get("comment") or ""),
        "journal_ref": str(raw.get("journal_ref") or ""),
        "code": str(raw.get("code") or ""),
        "project": str(raw.get("project") or ""),
        "topics": list(dict.fromkeys(topics)),
        "first_seen": str(raw.get("first_seen") or published),
        "links_checked": str(raw.get("links_checked") or ""),
    }


def load_archive(path: Path) -> dict[str, Any]:
    """Load the JSON archive; returns an empty archive if missing or legacy."""
    if not path.is_file() or path.stat().st_size == 0:
        return empty_archive()
    with path.open("r", encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict) or not isinstance(data.get("papers"), dict):
        LOG.warning("%s is not a schema-%d archive (legacy format?); starting a new archive", path, SCHEMA_VERSION)
        return empty_archive()
    archive = empty_archive()
    archive["updated_at"] = data.get("updated_at")
    archive["topics"] = data.get("topics") if isinstance(data.get("topics"), list) else []
    skipped = 0
    for raw in data["papers"].values():
        record = _clean_record(raw) if isinstance(raw, Mapping) else None
        if record is None:
            skipped += 1
            continue
        archive["papers"][record["id"]] = record
    if skipped:
        LOG.warning("skipped %d malformed paper records in %s", skipped, path)
    return archive


def sort_key(paper: Mapping[str, Any]) -> tuple[str, str]:
    return (paper.get("published", ""), paper.get("id", ""))


def sorted_papers(papers: Iterable[Mapping[str, Any]]) -> list[Mapping[str, Any]]:
    return sorted(papers, key=sort_key, reverse=True)


def serialize_archive(archive: Mapping[str, Any]) -> str:
    """Stable, diff-friendly JSON: one topic / paper per line, newest first."""
    dump = lambda value: json.dumps(value, ensure_ascii=False, separators=(",", ":"))  # noqa: E731
    lines = ["{"]
    lines.append(f'  "schema_version": {SCHEMA_VERSION},')
    lines.append(f'  "updated_at": {dump(archive.get("updated_at"))},')
    topics = archive.get("topics") or []
    if topics:
        lines.append('  "topics": [')
        lines.append(",\n".join(f"    {dump(t)}" for t in topics))
        lines.append("  ],")
    else:
        lines.append('  "topics": [],')
    papers = sorted_papers(archive.get("papers", {}).values())
    if papers:
        lines.append('  "papers": {')
        rows = []
        for paper in papers:
            record = {key: paper.get(key) for key in PAPER_KEYS}
            rows.append(f"    {dump(record['id'])}: {dump(record)}")
        lines.append(",\n".join(rows))
        lines.append("  }")
    else:
        lines.append('  "papers": {}')
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_if_changed(path: Path, content: str) -> bool:
    """Atomically write UTF-8 text with LF line endings; skip if unchanged."""
    if path.is_file():
        try:
            if path.read_text(encoding="utf-8") == content:
                return False
        except UnicodeDecodeError:
            pass
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise
    return True


def topics_metadata(cfg: Config) -> list[dict[str, str]]:
    return [{"slug": t.slug, "name": t.name, "description": t.description} for t in cfg.topics]


def merge_paper(papers: dict[str, dict[str, Any]], paper: Mapping[str, Any], topic_slug: str, today: str) -> bool:
    """Insert or update a paper; returns True if anything changed."""
    existing = papers.get(paper["id"])
    if existing is None:
        record = {key: paper.get(key, "") for key in PAPER_KEYS}
        record.update(topics=[topic_slug], first_seen=today, links_checked="")
        papers[paper["id"]] = record
        return True
    before = json.dumps(existing, sort_keys=True, ensure_ascii=False)
    for key in ("title", "authors", "n_authors", "published", "updated", "primary_category",
                "categories", "comment", "journal_ref"):
        if paper.get(key) not in (None, ""):
            existing[key] = paper[key]
        elif key in ("comment", "journal_ref"):
            existing[key] = ""
    # A link found in the metadata always wins; an existing link is never dropped.
    for key in ("code", "project"):
        if paper.get(key):
            existing[key] = paper[key]
    if topic_slug not in existing["topics"]:
        existing["topics"].append(topic_slug)
    return json.dumps(existing, sort_keys=True, ensure_ascii=False) != before


def normalize_topics(papers: dict[str, dict[str, Any]], cfg: Config) -> int:
    """Order topic memberships like the config and drop unknown topics.

    Papers that no longer belong to any configured topic are removed (they
    remain in the git history). Returns the number of removed papers.
    """
    order = {topic.slug: index for index, topic in enumerate(cfg.topics)}
    removed = 0
    for arxiv_id in list(papers):
        record = papers[arxiv_id]
        kept = sorted({t for t in record.get("topics", []) if t in order}, key=order.__getitem__)
        if not kept:
            del papers[arxiv_id]
            removed += 1
        else:
            record["topics"] = kept
    return removed


