def front_matter(fields: Mapping[str, Any]) -> str:
    lines = ["---", f"# {GENERATED_MARKER} - do not edit by hand"]
    for key, value in fields.items():
        if isinstance(value, bool):
            lines.append(f"{key}: {'true' if value else 'false'}")
        elif isinstance(value, int):
            lines.append(f"{key}: {value}")
        else:
            lines.append(f"{key}: {yaml_str(str(value))}")
    lines.append("---")
    return "\n".join(lines) + "\n"


@dataclass(frozen=True)
class TopicStats:
    count: int
    with_code: int
    oldest: str  # v1 submission date of the oldest tracked paper ("" if none)
    newest: str


@dataclass(frozen=True)
class SiteData:
    cfg: Config
    papers: tuple[Mapping[str, Any], ...]  # active papers, newest first
    by_topic: Mapping[str, tuple[Mapping[str, Any], ...]]
    stats: Mapping[str, TopicStats]
    updated_at: dt.datetime | None

    @property
    def topic_names(self) -> dict[str, str]:
        return {t.slug: t.name for t in self.cfg.topics}


def build_site_data(archive: Mapping[str, Any], cfg: Config) -> SiteData:
    known = {t.slug for t in cfg.topics}
    active = [p for p in archive.get("papers", {}).values() if any(t in known for t in p.get("topics", []))]
    papers = tuple(sorted_papers(active))
    by_topic: dict[str, tuple[Mapping[str, Any], ...]] = {}
    stats: dict[str, TopicStats] = {}
    for topic in cfg.topics:
        members = tuple(p for p in papers if topic.slug in p.get("topics", []))
        by_topic[topic.slug] = members
        oldest, newest = date_span(members)
        stats[topic.slug] = TopicStats(
            count=len(members),
            with_code=sum(1 for p in members if p.get("code")),
            oldest=oldest,
            newest=newest,
        )
    return SiteData(cfg, papers, by_topic, stats, parse_iso_utc(archive.get("updated_at") or ""))


def date_span(papers: Sequence[Mapping[str, Any]]) -> tuple[str, str]:
    """(oldest, newest) v1 submission dates of papers sorted newest first; ("", "") if empty."""
    if not papers:
        return "", ""
    return papers[-1]["published"], papers[0]["published"]


def _time_html(day: str) -> str:
    return f'<time datetime="{esc(day)}">{esc(day)}</time>'


def span_html(oldest: str, newest: str) -> str:
    """'from <oldest> to <newest>', or 'on <day>' when all papers share one date."""
    if not newest:
        return ""
    if not oldest or oldest == newest:
        return f"on {_time_html(newest)}"
    return f"from {_time_html(oldest)} to {_time_html(newest)}"


def span_compact_html(oldest: str, newest: str) -> str:
    """'<oldest> to <newest>' (or a single date) for compact labels such as topic cards."""
    if not newest:
        return ""
    if not oldest or oldest == newest:
        return _time_html(newest)
    return f"{_time_html(oldest)} to {_time_html(newest)}"


def _updated_html(data: SiteData) -> str:
    if data.updated_at is None:
        return "Not updated yet — run <code>python daily_arxiv.py</code> or the GitHub Actions workflow."
    stamp = data.updated_at.strftime("%Y-%m-%d %H:%M UTC")
    return f'Last updated <time datetime="{esc(iso_utc(data.updated_at))}">{esc(stamp)}</time>'


def _archive_status_html(data: SiteData) -> str:
    """'Last updated … · Papers submitted from <oldest> to <newest>' for the whole archive."""
    oldest, newest = date_span(data.papers)
    span = f" · Papers submitted {span_html(oldest, newest)}" if newest else ""
    return _updated_html(data) + span


