def in_github_actions() -> bool:
    return os.environ.get("GITHUB_ACTIONS") == "true"


def annotate(level: str, message: str) -> None:
    """Log a message and surface it as a GitHub Actions annotation."""
    getattr(LOG, "error" if level == "error" else "warning")(message)
    if in_github_actions():
        print(f"::{level}::{message}", flush=True)


def lookup_links(
    papers: Iterable[dict[str, Any]],
    resolver: HFLinkResolver,
    today: str,
) -> tuple[int, int]:
    """Query Hugging Face for papers without code; returns (checked, updated)."""
    checked = updated = 0
    for record in papers:
        result = resolver.lookup(record["id"])
        if result is None:
            if resolver.disabled or resolver.used >= resolver.max_lookups:
                break
            continue
        checked += 1
        code, project = result
        changed = False
        if code and code != record.get("code"):
            record["code"] = code
            changed = True
        if project and not record.get("project"):
            record["project"] = project
            changed = True
        record["links_checked"] = today
        updated += int(changed)
    return checked, updated


def run_fetch(cfg: Config, args: argparse.Namespace) -> int:
    archive = load_archive(cfg.data_file)
    papers: dict[str, dict[str, Any]] = archive["papers"]
    before = {k: json.dumps(v, sort_keys=True, ensure_ascii=False) for k, v in papers.items()}
    today = utc_now().date().isoformat()

    topics = list(cfg.topics)
    if args.topics:
        wanted = set(args.topics)
        unknown = wanted - {t.slug for t in topics}
        if unknown:
            raise ConfigError(f"unknown topic slug(s): {', '.join(sorted(unknown))}")
        topics = [t for t in topics if t.slug in wanted]

    client = make_arxiv_client(cfg)
    new_ids: set[str] = set()
    failed: list[str] = []
    for index, topic in enumerate(topics):
        try:
            fetched = fetch_topic(client, topic, cfg, max_results=args.max_results)
        except ArxivRateLimited as exc:
            # Further requests would only prolong the rate limit; the next run catches up.
            skipped = [t.slug for t in topics[index:]]
            failed.extend(skipped)
            annotate("warning", f"topic '{topic.slug}' failed: {exc}; skipped the remaining {len(skipped) - 1} topic(s)")
            break
        except Exception as exc:  # network/API errors must not abort the whole run
            failed.append(topic.slug)
            annotate("warning", f"topic '{topic.slug}' failed: {type(exc).__name__}: {exc}")
            continue
        added = 0
        for paper in fetched:
            if paper["id"] not in papers:
                new_ids.add(paper["id"])
                added += 1
            merge_paper(papers, paper, topic.slug, today)
        LOG.info("[%s] %d papers fetched, %d new", topic.slug, len(fetched), added)

    if len(failed) == len(topics):
        annotate("error", "all arXiv queries failed; the archive and site were left unchanged")
        return 2

    removed = normalize_topics(papers, cfg)
    if removed:
        LOG.info("removed %d papers that no longer belong to any configured topic", removed)

    if cfg.huggingface_lookup and not args.no_hf:
        resolver = HFLinkResolver(max_lookups=cfg.max_lookups_per_run)
        pending = [papers[i] for i in sorted(new_ids, reverse=True) if i in papers and not papers[i].get("code")]
        checked, found = lookup_links(pending, resolver, today)
        LOG.info("Hugging Face: %d papers checked, %d gained a code/project link", checked, found)
    for arxiv_id in new_ids:
        if arxiv_id in papers and papers[arxiv_id].get("code") and not papers[arxiv_id].get("links_checked"):
            papers[arxiv_id]["links_checked"] = today

    after = {k: json.dumps(v, sort_keys=True, ensure_ascii=False) for k, v in papers.items()}
    changed = before != after
    written = write_outputs(archive, cfg, data_changed=changed)
    LOG.info("%d new papers, %d total; %d files written", len(new_ids), len(papers), written)
    if failed:
        annotate("warning", f"{len(failed)} of {len(topics)} topics failed: {', '.join(failed)}")
    return 0


def run_update_links(cfg: Config, args: argparse.Namespace) -> int:
    archive = load_archive(cfg.data_file)
    papers: dict[str, dict[str, Any]] = archive["papers"]
    normalize_topics(papers, cfg)
    if not cfg.huggingface_lookup or args.no_hf:
        LOG.info("Hugging Face lookups are disabled; nothing to do")
        return 0
    today_date = utc_now().date()
    cutoff = (today_date - dt.timedelta(days=cfg.recheck_days)).isoformat()
    today = today_date.isoformat()
    candidates = [
        p for p in sorted_papers(papers.values())
        if not p.get("code") and p.get("published", "") >= cutoff and p.get("links_checked") != today
    ]
    LOG.info("%d papers without code submitted since %s", len(candidates), cutoff)
    links_before = {k: (v.get("code"), v.get("project")) for k, v in papers.items()}
    resolver = HFLinkResolver(max_lookups=cfg.max_lookups_per_run)
    checked, found = lookup_links(candidates, resolver, today)  # type: ignore[arg-type]
    links_after = {k: (v.get("code"), v.get("project")) for k, v in papers.items()}
    # Only new links count as a data update; `links_checked` is bookkeeping.
    written = write_outputs(archive, cfg, data_changed=links_before != links_after)
    LOG.info("checked %d papers, %d gained links; %d files written", checked, found, written)
    return 0


def run_render(cfg: Config, args: argparse.Namespace) -> int:
    archive = load_archive(cfg.data_file)
    normalize_topics(archive["papers"], cfg)
    written = write_outputs(archive, cfg, data_changed=False)
    LOG.info("site rendered; %d files written", written)
    return 0


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Photo Geometry arXiv Daily: fetch new arXiv papers and build the website.",
    )
    parser.add_argument("--config", "--config_path", dest="config", default=None,
                        help="path to config.yaml (default: config.yaml next to this script)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--update-links", "--update_paper_links", dest="update_links", action="store_true",
                      help="re-check code links of recent papers on the Hugging Face Papers API")
    mode.add_argument("--render-only", action="store_true",
                      help="rebuild the website from the JSON archive without network access")
    parser.add_argument("--topics", nargs="+", metavar="SLUG", help="only fetch these topic slugs")
    parser.add_argument("--max-results", type=int, default=None, metavar="N",
                        help="override arxiv.max_results_per_topic for this run")
    parser.add_argument("--no-hf", action="store_true", help="skip Hugging Face code-link lookups")
    parser.add_argument("-v", "--verbose", action="store_true", help="debug logging")
    args = parser.parse_args(argv)
    if args.max_results is not None and args.max_results < 1:
        parser.error("--max-results must be >= 1")
    return args


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )
    config_path = Path(args.config) if args.config else Path(__file__).resolve().parent / "config.yaml"
    try:
        cfg = load_config(config_path)
        if args.render_only:
            return run_render(cfg, args)
        if args.update_links:
            return run_update_links(cfg, args)
        return run_fetch(cfg, args)
    except ConfigError as exc:
        annotate("error", f"configuration error: {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
