        f"{filter_box}\n"
        f'<table class="pg-papers" id="{esc(table_id)}">'
        f'<caption class="pg-sr-only">{esc(caption)}</caption>'
        '<thead><tr><th scope="col" class="pg-col-date">Submitted</th><th scope="col" class="pg-col-title">Title</th>'
