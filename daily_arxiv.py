def paper_from_result(result: Any) -> dict[str, Any]:
    """Convert an ``arxiv.Result`` into the archive record format."""
    arxiv_id = strip_version(result.get_short_id())
    title = tex_to_text(result.title or "")
    authors_all = [tex_to_text(str(getattr(a, "name", a))) for a in (result.authors or [])]
    authors_all = [a for a in authors_all if a]
    comment = tex_to_text(result.comment or "")
    journal_ref = tex_to_text(getattr(result, "journal_ref", None) or "")
    code, project = extract_links(f"{result.summary or ''} {result.comment or ''}")
    categories = list(dict.fromkeys(c for c in (result.categories or []) if c))
    primary = result.primary_category or (categories[0] if categories else "")
    return {
        "id": arxiv_id,
        "title": truncate(title, MAX_TITLE_CHARS),
        "authors": [truncate(a, 100) for a in authors_all[:MAX_AUTHORS_STORED]],
        "n_authors": len(authors_all),
        "published": result.published.date().isoformat(),
        "updated": result.updated.date().isoformat(),
        "primary_category": primary,
        "categories": categories,
        "comment": truncate(comment, MAX_COMMENT_CHARS),
        "journal_ref": truncate(journal_ref, MAX_JOURNAL_REF_CHARS),
        "code": code,
        "project": project,
    }


def _add_default_timeout(session: Any, timeout: tuple[float, float]) -> None:
    """Give every request of a requests.Session a timeout unless one is passed.

    The arxiv package issues its requests without a timeout, so a stalled
    connection could otherwise block a run until the CI job is cancelled.
    """
    if not isinstance(session, requests.Session) or getattr(session, "_pg_timeout", False):
        return
    original = session.request

    def request(method: str, url: str, **kwargs: Any) -> requests.Response:
        kwargs.setdefault("timeout", timeout)
        return original(method, url, **kwargs)

    session.request = request  # type: ignore[method-assign]
    session._pg_timeout = True  # type: ignore[attr-defined]


def make_arxiv_client(cfg: Config) -> Any:
    import arxiv  # imported lazily so --render-only works without the package

    client = arxiv.Client(page_size=100, delay_seconds=cfg.request_delay_seconds, num_retries=cfg.num_retries)
    _add_default_timeout(getattr(client, "_session", None), (15.0, 90.0))
    return client


#: HTTP statuses with which the arXiv API signals "too many requests / try later".
RATE_LIMIT_STATUSES = (429, 503)
#: Extra waits (seconds) before re-trying a rate-limited query; the arxiv
#: package's own retries are only `request_delay_seconds` apart.
RATE_LIMIT_BACKOFF_SECONDS = (30, 90)


class ArxivRateLimited(RuntimeError):
    """The arXiv API still answered 429/503 after the back-off retries."""


def fetch_topic(
    client: Any,
    topic: Topic,
    cfg: Config,
    max_results: int | None = None,
    sleep: Callable[[float], None] | None = None,
) -> list[dict[str, Any]]:
    """Fetch the newest papers for one topic.

    The arXiv API occasionally answers with a spurious empty page, so an empty
    result is retried twice before being accepted. Rate limiting (HTTP 429/503)
    is retried after longer waits and then raised as ``ArxivRateLimited``.
    """
    import arxiv

    sleep = sleep if sleep is not None else time.sleep  # looked up now, so tests can patch it
    query = build_query(topic, cfg.categories)
    limit = max_results or cfg.max_results_per_topic
    LOG.info("[%s] query: %s", topic.slug, query)
    empty_retries = rate_retries = 0
    while True:
        search = arxiv.Search(
            query=query,
            max_results=limit,
            sort_by=arxiv.SortCriterion.SubmittedDate,
            sort_order=arxiv.SortOrder.Descending,
        )
        try:
            papers = [paper_from_result(result) for result in client.results(search)]
        except arxiv.HTTPError as exc:
            if getattr(exc, "status", None) not in RATE_LIMIT_STATUSES:
                raise
            if rate_retries >= len(RATE_LIMIT_BACKOFF_SECONDS):
                raise ArxivRateLimited(f"arXiv API still answered HTTP {exc.status} after back-off retries") from exc
            wait = RATE_LIMIT_BACKOFF_SECONDS[rate_retries]
            rate_retries += 1
            LOG.warning("[%s] arXiv API answered HTTP %s (rate limit); retrying in %ss", topic.slug, exc.status, wait)
            sleep(wait)
            continue
        if papers or empty_retries >= 2:
            return papers
        empty_retries += 1
        LOG.warning("[%s] arXiv returned no results; retrying in %ss", topic.slug, 10 * empty_retries)
        sleep(10 * empty_retries)


