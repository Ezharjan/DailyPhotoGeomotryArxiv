def _accent(base: str, mark: str) -> str:
    letter = "i" if base == "\\i" else base
    return unicodedata.normalize("NFC", letter + _ACCENTS[mark])


def _script(match: re.Match[str], table: dict[int, int], allowed: set[str], marker: str) -> str:
    body = (match.group(1) if match.group(1) is not None else match.group(2)).strip()
    if body in ("°", "∘"):
        return "°"
    if body and all(ch in allowed for ch in body):
        return body.translate(table)
    if marker == "^" and body and any(ch.isalnum() for ch in body):
        return f"^{body}"
    return body


def _tex_segment(segment: str, math: bool) -> str:
    s = _ACCENT_SYMBOL_RE.sub(lambda m: _accent(m.group(2) or m.group(3), m.group(1)), segment)
    s = _ACCENT_LETTER_RE.sub(lambda m: _accent(m.group(2) or m.group(3), m.group(1)), s)
    s = _SPECIAL_LETTER_RE.sub(lambda m: _SPECIAL_LETTERS[m.group(1)], s)
    s = re.sub(r"\\[,;:! ]", " ", s)
    s = re.sub(r"\\q?quad(?![A-Za-z])", " ", s)
    if math:
        s = _DEGREE_RE.sub("°", s)
    s = _MACRO_RE.sub(lambda m: _GREEK.get(m.group(1), _SYMBOLS.get(m.group(1), m.group(0))), s)
    if math:
        s = _SUP_RE.sub(lambda m: _script(m, _SUPERSCRIPTS, _SUPERSCRIPT_OK, "^"), s)
        s = _SUB_RE.sub(lambda m: _script(m, _SUBSCRIPTS, _SUBSCRIPT_OK, "_"), s)
    # \LaTeX{} -> LaTeX; \textbf{x} / \mathcal{L} / unknown \cmd{x} -> x; \cmd -> cmd.
    s = re.sub(r"\\([A-Za-z]+)\s*\{\}", r"\1", s)
    s = _FORMAT_CMD_RE.sub("", s)
    s = _UNKNOWN_CMD_ARG_RE.sub("", s)
    s = re.sub(r"\\([A-Za-z]+)", r"\1", s)
    return s.replace("{", "").replace("}", "").replace("\\", "")


def tex_to_text(text: str) -> str:
    """Convert the TeX found in arXiv titles, names and comments to Unicode.

    Text mode: accents (``M\\"uller`` -> Müller), escaped specials (``\\&``),
    font commands, TeX dashes/quotes. Math mode (between balanced ``$``):
    additionally Greek letters, symbols, degrees and super/subscripts
    (``$360^\\circ$`` -> 360°, ``$\\mathcal{L}_1$`` -> L₁). Unknown macros are
    reduced to their argument or name; plain text is only whitespace-normalized.
    """
    if not text:
        return ""
    s = str(text)
    if not any(token in s for token in ("\\", "$", "--", "``", "''")):
        return _normalize_space(s)
    for raw, placeholder in _PROTECTED.items():
        s = s.replace(raw, placeholder)
    parts = s.split("$")
    if len(parts) % 2 == 1:  # balanced dollars: odd-indexed parts are math
        s = "".join(_tex_segment(part, math=bool(i % 2)) for i, part in enumerate(parts))
    else:
        s = _tex_segment(s, math=False)
    s = s.replace("---", "—").replace("--", "–").replace("``", "“").replace("''", "”")
    for placeholder, char in _RESTORED.items():
        s = s.replace(placeholder, char)
    return _normalize_space(s)


def truncate(text: str, limit: int) -> str:
    text = _normalize_space(text)
    if len(text) <= limit:
        return text
    cut = text[: limit - 1].rsplit(" ", 1)[0] if " " in text[: limit - 1] else text[: limit - 1]
    return cut.rstrip(" ,;:.") + "…"


def strip_version(arxiv_id: str) -> str:
    """'2611.04822v2' -> '2611.04822'; 'math/0211159v1' -> 'math/0211159'."""
    return VERSION_SUFFIX_RE.sub("", arxiv_id.strip())


