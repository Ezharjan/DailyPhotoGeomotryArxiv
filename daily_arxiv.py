def esc(value: Any) -> str:
    """HTML-escape text and neutralize Liquid delimiters ({{ }}, {% %})."""
    return html.escape(str(value), quote=True).replace("{", "&#123;").replace("}", "&#125;")


def yaml_str(value: str) -> str:
    """A YAML-safe double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(value, ensure_ascii=False)


def fmt_int(value: int) -> str:
    return f"{value:,}"


def format_authors(paper: Mapping[str, Any], shown: int = 3) -> tuple[str, str]:
    """('A, B, C et al.', 'full author list for the tooltip')."""
    authors = list(paper.get("authors") or [])
    total = max(int(paper.get("n_authors") or 0), len(authors))
    if not authors:
        return "", ""
    short = ", ".join(authors[:shown]) + (" et al." if total > shown else "")
    full = ", ".join(authors)
    if total > len(authors):
        full += f", and {total - len(authors)} more"
    return short, full


