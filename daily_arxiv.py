def _keyword_list(phrases: Sequence[str]) -> str:
    return ", ".join(f"<code>{esc(p)}</code>" for p in phrases)


def render_topic_page(data: SiteData, topic: Topic, nav_order: int) -> str:
    cfg = data.cfg
    papers = data.by_topic[topic.slug]
    st = data.stats[topic.slug]
    shown = papers[: cfg.topic_page_max_papers]
    query = build_query(topic, cfg.categories)
    title_only = [p for p in topic.title_keywords if phrase_key(p) not in {phrase_key(k) for k in topic.keywords}]
